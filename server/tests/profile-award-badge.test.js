const { test } = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const Grant = require('../models/AwardGrant');
const authPath = require.resolve('../middleware/auth');
require(authPath);
const original = require.cache[authPath].exports;
let account;
require.cache[authPath].exports = (req, res, next) => { req.user = account; next(); };
const router = require('../routes/users');
require.cache[authPath].exports = original;
test('profile award badge validates ownership and uses server data', async t => {
 const app = express(); app.use(express.json()); app.use('/users', router);
 const server = app.listen(0, '127.0.0.1');
 t.after(() => { server.closeAllConnections(); server.close(); });
 await new Promise(r => server.once('listening', r));
 let saved = 0, filter, owned = false;
 const id = '507f1f77bcf86cd799439012';
 account = { _id: '507f1f77bcf86cd799439011', save: async () => { saved++; }, populate: async () => {} };
 t.mock.method(Grant, 'findOne', value => { filter = value; return { populate: async () => owned ? { award: { _id: id, name: 'Earned', model: 'medal', color: '#ffc65c' } } : null }; });
 const put = displayedTag => fetch(`http://127.0.0.1:${server.address().port}/users/profile`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ displayedTag }) });
 assert.equal((await put({ type: 'award', award: { id: 'bad' } })).status, 400);
 assert.equal((await put({ type: 'award', award: { id } })).status, 400);
 assert.equal(saved, 0); assert.equal(filter.user, account._id); assert.equal(filter.revoked, false);
 owned = true;
 let response = await put({ type: 'award', award: { id, name: 'Forged', color: '#000000' } });
 assert.equal(response.status, 200);
 assert.deepEqual((await response.json()).displayedTag.award, { id, name: 'Earned', model: 'medal', color: '#ffc65c' });
 response = await put({ type: 'badge' });
 assert.equal(response.status, 200); assert.equal(account.displayedTag.award, null);
});
